/* =====================================================================
 利用できる rule.type:
  - add_increase     : 転嫁後売単価 = 現売単価 +(新仕入 − 現仕入)  ← 値上げ分を上乗せ（利益額キープ）
  - keep_margin_rate : 現在の粗利率を維持して再計算
                        転嫁後売単価 = 新仕入 ÷(1 − 現粗利率)
  - markup           : 転嫁後売単価 = 新仕入 × factor（factor=掛率, 例 1.25）
  - keep_sell        : 値上げしない（現売単価のまま。粗利は減る）

 when（条件）に使えるキー:
  - customer          : 得意先名（完全一致）
  - customerCode      : 得意先コード（完全一致）
  - product           : 販売実績商品名（部分一致）
  - productCodePrefix : 商品コードの先頭一致
  - maker             : 仕入先（メーカー）名（部分一致）
 ===================================================================== */
