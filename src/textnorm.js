// =====================================================================
//  文字の正規化（全角/半角・大文字小文字のゆれ吸収）
//  弊社登録は半角カナ・半角英数、メーカーは全角の場合がある。
//  NFKC で 全角英数→半角英数 / 半角カナ→全角カナ(濁点合成) などを統一し、
//  商品名・コードの照合を「全角・半角を区別せず」行えるようにする。
// =====================================================================

// NFKC 正規化のみ（表示は変えず、比較用に整える）
function nfkc(s) {
  return String(s == null ? '' : s).normalize('NFKC');
}

// 照合キー: NFKC ＋ 表記ゆれ吸収 ＋ 空白除去 ＋ 小文字化
//  （全角/半角・大小・空白の差を無視。壜/瓶=ビン のような読み同一の表記ゆれも統一）
function normName(s) {
  return nfkc(s)
    .replace(/[壜瓶]/g, 'ビン') // タレ壜 = タレビン（メーカー/販売実績の表記差を吸収）
    .replace(/篏/g, '嵌')       // 篏合蓋(販売実績) = 嵌合蓋(メーカー) の異体字を統一
    .replace(/[\s　]+/g, '')
    .toLowerCase();
}

module.exports = { nfkc, normName };
